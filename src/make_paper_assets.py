def style_run(run, size: float, bold: bool = False, east_asia: str = "宋体") -> None:
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), east_asia)


def set_cell(cell, text: str, bold: bool = False, size: float = 9.5) -> None:
    cell.text = ""
    style_run(cell.paragraphs[0].add_run(text), size, bold)
    cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER


def add_table(doc: Document, caption: str, cols: list[str], rows: list[list[str]], note: str = "") -> None:
    style_run(doc.add_paragraph().add_run(caption), 10.5, bold=True, east_asia="黑体")
    t = doc.add_table(rows=1, cols=len(cols))
    t.style = "Table Grid"
    for i, c in enumerate(cols):
        set_cell(t.rows[0].cells[i], c, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            set_cell(cells[i], v)
    if note:
        style_run(doc.add_paragraph().add_run(note), 9)
    doc.add_paragraph()


def build_tables(lang: str) -> Path:
    t = L[lang]
    zh = lang == "zh"
    doc = Document()
    doc.add_heading(t["doc_title"], level=1)

    rows = []
    for name, p, r, f, s in ner_rows():
        rows.append([name if zh else ENTITY_EN.get(name, name), p, r, f, s])
    add_table(doc, t["t1"], t["t1_cols"], rows)

    boot = load_json("bootstrap_query_f1.json")["relations"]
    _, sens = ablation_data()
    rows = []
    for rel, b in boot.items():
        bd = b["bootstrap_by_disease"]
        rows.append([
            rel if zh else REL_EN[rel],
            str(b["n_query"]),
            f"{f3(b['f1_raw'])} {ci(bd['g_raw_ci95'])}",
            f"{f3(b['f1_norm'])} {ci(bd['g_norm_ci95'])}",
            f"{b['delta']:+.3f} {signed_ci(bd['delta_ci95'])}",
            f"{b['n_improved']}/{b['n_worse']}/{b['n_same']}",
            "< 0.001" if b["p_sign_flip_two_sided"] < 0.001 else f"{b['p_sign_flip_two_sided']:.3f}",
        ])
    drug, surg = (" → ".join(f"{float(v):.3f}" for v in pair.split("→")) for pair in sens["+alias"])
    cons = (f" 用药 {drug}，手术 {surg}。" if zh else f" drug {drug}, surgery {surg}.")
    add_table(doc, t["t2"], t["t2_cols"], rows, t["t2_note"] + cons)

    abl, _ = ablation_data()
    boot_drug, boot_surg = boot["使用药物"]["f1_raw"], boot["实施手术"]["f1_raw"]
    rows = [[t["t3_raw"], f3(boot_drug), f3(boot_surg), "—", "—"]]
    for mode, d, s, hit, merged in abl:
        label = ABLATION_ROWS[mode][0 if zh else 1]
        rows.append([label, f3(d), f3(s), f3(hit), str(merged)])
    add_table(doc, t["t3"], t["t3_cols"], rows)

    cdn = load_json("cdn_baselines.json")["methods"]
    rows = []
    for key, cat, name_zh, name_en in CDN_ROWS:
        m = cdn[key]
        rows.append([
            name_zh if zh else name_en,
            t["cat_free"] if cat == "free" else t["cat_sup"],
            f3(m["accuracy_strict"]),
            f3(m["accuracy"]),
            f3(m["coverage"]),
            f3(m["precision_answered"]),
            f3(m["set_f1"]),
        ])
    add_table(doc, t["t4"], t["t4_cols"], rows, t["t4_note"])

    sup = load_json("supervised_graph.json")["modes"]
    rows = []
    for key, name_zh, name_en in SUP_ROWS:
        m = sup[key]
        bw = m["vs_off_better_worse"]
        rows.append([
            name_zh if zh else name_en,
            f3(m["icd_hit_rate"]),
            f3(m["fixed_gold"]["使用药物"][1]),
            f3(m["fixed_gold"]["实施手术"][1]),
            "—" if key == "off" else f"{bw['使用药物'][0]}/{bw['使用药物'][1]}",
            "—" if key == "off" else f"{bw['实施手术'][0]}/{bw['实施手术'][1]}",
        ])
    add_table(doc, t["t5"], t["t5_cols"], rows, t["t5_note"])

    man = load_json("manual_norm_acc.json")
    by_src = man["by_source"]
    n_all = man["n_labeled"]
    n_kept = by_src["heuristic"]["n"]
    n_linked = n_all - n_kept
    k_all = round(man["acc"] * n_all)
    k_linked = round(man["acc_linked"] * n_linked)
    k_kept = round(man["acc_kept"] * n_kept)
    rows = []
    for key, k, n in [("all", k_all, n_all), ("linked", k_linked, n_linked), ("kept", k_kept, n_kept)]:
        rows.append([t["manual_rows"][key], f"{k}/{n}", f3(k / n), ci(wilson(k, n))])
    for src, v in sorted(by_src.items(), key=lambda kv: -kv[1]["n"]):
        if src == "heuristic":
            continue
        k = round(v["acc"] * v["n"])
        rows.append([f"  {src}", f"{k}/{v['n']}", f3(v["acc"]), ci(wilson(k, v["n"]))])
    add_table(doc, t["t6"], t["t6_cols"], rows, t["t6_note"])

    path = OUT / f"tables_{lang}.docx"
    doc.save(path)
    return path


