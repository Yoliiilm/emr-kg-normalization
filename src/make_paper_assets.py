def ner_rows() -> list[list[str]]:
    rows = []
    pat = re.compile(r"^\s*(\S+(?: avg)?)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+(\d+)\s*$")
    for line in (METRICS / "test_report.txt").read_text(encoding="utf-8").splitlines():
        m = pat.match(line)
        if m and m.group(1) != "weighted avg":
            rows.append([m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)])
    return rows


def ablation_data() -> tuple[list[tuple[str, float, float, float, int]], dict[str, tuple[str, str]]]:
    text = (METRICS / "ablation.txt").read_text(encoding="utf-8")
    table = text.split("简表（汇报用）", 1)[1].split("标准答案敏感性", 1)[0]
    rows = []
    for line in table.strip().splitlines()[1:]:
        parts = line.split("\t")
        if len(parts) == 5:
            rows.append((parts[0], float(parts[1]), float(parts[2]), float(parts[3]), int(parts[4])))
    sens = {}
    for line in text.split("标准答案敏感性", 1)[1].splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and "→" in parts[1]:
            sens[parts[0]] = (parts[1], parts[2])
    return rows, sens


