def subgraph_data(max_aliases: int = 5, max_drugs: int = 8):
    cmap = json.loads((GRAPH / "canonical_map.json").read_text(encoding="utf-8"))
    aliases = []
    for key, meta in cmap.items():
        etype, surface = key.split("::", 1)
        to = meta.get("to")
        targets = to if isinstance(to, list) else [to]
        if etype == "疾病和诊断" and DEMO_CANONICAL in targets and surface.strip() != DEMO_CANONICAL:
            aliases.append(surface.strip())

    raw_nodes = {r["id:ID"]: r for r in read_csv("nodes_pred_test.csv")}
    alias_ids = [f"疾病和诊断::{a}" for a in aliases if f"疾病和诊断::{a}" in raw_nodes]
    alias_ids.sort(key=lambda i: -int(raw_nodes[i]["mention_count:int"]))
    alias_ids = alias_ids[:max_aliases]

    raw_edges = defaultdict(dict)
    for r in read_csv("relations_pred_test.csv"):
        if r[":TYPE"] == "使用药物" and r[":START_ID"] in alias_ids:
            raw_edges[r[":START_ID"]][r[":END_ID"].split("::", 1)[1]] = int(r["weight:int"])

    norm_edges = {}
    canon_id = f"疾病和诊断::{DEMO_CANONICAL}"
    for r in read_csv("relations_pred_test_norm.csv"):
        if r[":TYPE"] == "使用药物" and r[":START_ID"] == canon_id:
            norm_edges[r[":END_ID"].split("::", 1)[1]] = int(r["weight:int"])
    norm_drugs = [d for d, _ in sorted(norm_edges.items(), key=lambda kv: -kv[1])[:max_drugs]]
    raw_drug_weight = defaultdict(int)
    for edges in raw_edges.values():
        for d, w in edges.items():
            raw_drug_weight[d] += w
    raw_drugs = [d for d, _ in sorted(raw_drug_weight.items(), key=lambda kv: -kv[1])[:max_drugs]]
    drug_alias = {}
    for d in raw_drugs:
        meta = cmap.get(f"药物::{d}", {})
        to = meta.get("to")
        if to and to != d and to in norm_drugs:
            drug_alias[d] = to
    return [i.split("::", 1)[1] for i in alias_ids], raw_edges, norm_edges, raw_drugs, norm_drugs, drug_alias


def fig_subgraph(lang: str) -> tuple[Path, dict]:
    t = L[lang]
    aliases, raw_edges, norm_edges, raw_drugs, norm_drugs, drug_alias = subgraph_data()
    fig, (axl, axr) = plt.subplots(1, 2, figsize=(14, 5.6), gridspec_kw={"width_ratios": [1, 1.25]})
    dis_c, drug_c, can_c = "#F4CCCC", "#D9EAD3", "#FCE5CD"
    alias_style = dict(arrowstyle="-|>", linestyle="--", color="#C0601A", linewidth=0.9)

    def node(ax, x, y, label, color, size=9):
        return ax.text(x, y, label, ha="center", va="center", fontsize=size, zorder=3,
                       bbox=dict(boxstyle="round,pad=0.35", facecolor=color, edgecolor="#555555"))

    def link(ax, src, dst, **style):
        ax.annotate("", xy=dst.get_position(), xytext=src.get_position(), zorder=1,
                    arrowprops=dict(patchA=src.get_bbox_patch(), patchB=dst.get_bbox_patch(),
                                    shrinkA=0, shrinkB=0, **style))

    def spread(i, n, top=0.88, span=0.76):
        return 0.5 if n == 1 else top - i * (span / (n - 1))

    edge_style = dict(arrowstyle="-", color="#888888", linewidth=0.9)
    for ax in (axl, axr):
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.axis("off")

    alias_y = [spread(j, len(aliases)) for j in range(len(aliases))]
    raw_drug_nodes = {d: node(axl, 0.85, spread(i, len(raw_drugs), 0.75, 0.5), d, drug_c)
                      for i, d in enumerate(raw_drugs)}
    for j, a in enumerate(aliases):
        src = node(axl, 0.22, alias_y[j], a, dis_c)
        for d in raw_edges.get(f"疾病和诊断::{a}", {}):
            if d in raw_drug_nodes:
                link(axl, src, raw_drug_nodes[d], **edge_style)
    axl.set_title(t["fig3_raw"], fontsize=10.5)

    canon = node(axr, 0.4, 0.5, DEMO_CANONICAL, can_c, size=10)
    for j, a in enumerate(aliases):
        link(axr, node(axr, 0.12, alias_y[j], a, dis_c, size=8.5), canon, **alias_style)
    axr.text(0.27, 0.95, t["fig3_alias"], fontsize=8, color="#C0601A", ha="center")
    norm_drug_nodes = {}
    for i, d in enumerate(norm_drugs):
        norm_drug_nodes[d] = node(axr, 0.72, spread(i, len(norm_drugs), 0.7, 0.4), d, drug_c)
        link(axr, canon, norm_drug_nodes[d], arrowstyle="-", color="#555555",
             linewidth=0.6 + 0.25 * math.log1p(norm_edges[d]))
    axr.text(0.57, 0.33, t["fig3_drug"], fontsize=8, color="#555555", ha="center")
    for k, (surface, target) in enumerate(drug_alias.items()):
        ty = norm_drug_nodes[target].get_position()[1]
        y = ty + (0.14 if ty >= 0.5 else -0.14) * (k + 1)
        link(axr, node(axr, 0.93, y, surface, drug_c, size=8.5), norm_drug_nodes[target], **alias_style)
    axr.set_title(t["fig3_norm"], fontsize=10.5)
    fig.canvas.draw()

    path = OUT / f"fig3_subgraph_{lang}.png"
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    info = {
        "aliases": aliases,
        "raw_drugs": raw_drugs,
        "norm_drugs": norm_drugs,
        "drug_alias": drug_alias,
    }
    return path, info


